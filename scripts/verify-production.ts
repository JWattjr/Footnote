import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';

const url=process.env.FOOTNOTE_URL??'https://footnote-genlayer.vercel.app';
const local=JSON.parse(readFileSync('public/deployment.json','utf8'));
const stamp=Date.now();
const responses=await Promise.all(['/?note=temperature-update-2025','/deployment.json','/api/feed'].map(path=>fetch(url+path+(path.includes('?')?'&':'?')+'verification='+stamp,{cache:'no-store',signal:AbortSignal.timeout(45000)})));
for(const response of responses)assert.equal(response.status,200,response.url);
const html=await responses[0].text();
assert.ok(html.includes('Public demo: 15-minute appeal window'));
assert.ok(html.includes('production default: 72 hours'));
const deployed=await responses[1].json();
const feed=await responses[2].json();
assert.equal(deployed.generation,3);
assert.ok(deployed.additionalProofs.completedAt);
for(const key of ['contracts','transactions','timing','unproven','accounting','legacyCleanup','postProofAccounting','historicalEscrowAccounting'])assert.deepEqual(deployed[key],local[key],key);
assert.deepEqual(feed.addresses,local.contracts);
assert.deepEqual(deployed.additionalProofs.balances.finish,local.additionalProofs.balances.finish);
assert.deepEqual(feed.unproven,local.unproven);
assert.equal(feed.notes.length,4);
for(const note of feed.notes)assert.deepEqual(note,local.states[note.id],note.id);
const changed=feed.notes.find((note:{id:string})=>note.id==='temperature-update-2025');
assert.equal(changed.version,2);
assert.equal(changed.history[0].decision.evidence_label,'UNSUPPORTED');
assert.equal(changed.history[1].decision.evidence_label,'SUPPORTED');
assert.ok(changed.history[1].decision.citations.some((citation:{url:string})=>citation.url==='https://science.nasa.gov/earth/explore/earth-indicators/global-temperature/'));
const report={checkedAt:new Date().toISOString(),url,statuses:responses.map(response=>({url:response.url,status:response.status})),generation:deployed.generation,addresses:deployed.contracts,receiptCount:Object.keys(deployed.transactions).length,notes:feed.notes.map((note:{id:string;version:number;history:{version:number;decision:{evidence_label:string;sources:string[]}}[]})=>({id:note.id,version:note.version,history:note.history.map(entry=>({version:entry.version,label:entry.decision.evidence_label,sources:entry.decision.sources}))})),historicalBalances:deployed.additionalProofs.balances.finish,balances:deployed.postProofAccounting?.current??deployed.additionalProofs.balances.finish,timing:deployed.timing,unproven:deployed.unproven};
writeFileSync('docs/proofs/production-verification.json',JSON.stringify(report,null,2)+'\n');
console.log('Production verified: generation 3, every current hash, four finalized notes, retained label-change history, exact recorded balances and timing disclosure.');
